// Regenerates netlify/functions/_pricePlanMap.js from src/constants/plans.js.
//
// The functions folder is CommonJS-scoped (netlify/functions/package.json)
// and can't `require()` an ES module in src/, so the Stripe priceId -> planId
// map used by create-checkout.js to validate what a customer is actually
// paying for is duplicated there as a plain object literal. Run this after
// editing src/constants/plans.js's `stripe` fields:
//
//   node scripts/generate-price-plan-map.js
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function main() {
  const { PLANS } = await import("../src/constants/plans.js");
  const map = {};
  for (const p of PLANS) {
    if (p.stripe?.monthly) map[p.stripe.monthly] = p.id;
    if (p.stripe?.yearly)  map[p.stripe.yearly]  = p.id;
  }

  const lines = Object.entries(map)
    .map(([priceId, planId]) => `  "${priceId}": "${planId}",`)
    .join("\n");

  const out = `// AUTO-GENERATED by scripts/generate-price-plan-map.js — do not edit by hand.
// Source of truth: src/constants/plans.js (the \`stripe\` field on each plan).
// Regenerate after changing that file: node scripts/generate-price-plan-map.js
//
// Used by create-checkout.js to derive the real plan from the Stripe price
// actually being charged, instead of trusting a client-supplied planId that
// could be set to a higher-value plan than the price paid for.
"use strict";

module.exports = {
${lines}
};
`;

  const outPath = path.join(__dirname, "..", "netlify", "functions", "_pricePlanMap.js");
  fs.writeFileSync(outPath, out);
  console.log(`Wrote ${Object.keys(map).length} price->plan mappings to ${outPath}`);
}

main().catch(err => { console.error(err); process.exit(1); });
